function writeTranslationFile(filename, varName, transMap) {
  const filePath = path.join(__dirname, '../src/i18n/translations', filename);
  let fileContent = `import { TranslationDictionary } from './en';\n\nexport const ${varName}: TranslationDictionary = {\n`;

  // Write every key from en.ts
  for (const key of Object.keys(enDict)) {
    const val = transMap[key] || enDict[key];
    const escapedVal = val.replace(/'/g, "\\'");
    fileContent += `  '${key}': '${escapedVal}',\n`;
  }

  fileContent += `};\n`;
  fs.writeFileSync(filePath, fileContent, 'utf8');
  console.log(`Wrote ${filename} with ${Object.keys(enDict).length} keys.`);
}

